def test_react_this_refs_repair_is_narrow_and_comment_string_safe(tmp_path: Path) -> None:
    root = tmp_path / "react-repair"
    root.mkdir()
    source = (
        "class Demo extends React.Component {\n"
        "  run() { this.refs.input.focus(); const s = 'this.refs.input'; }\n"
        "  render() { return <input ref={(node) => { this.refs.input = node; }} />; }\n"
        "}\n"
        "const pattern = /this.refs.input/;\n"
        "// this.refs.input stays documentary\n"
        "// ref={(node) => { this.refs.fake = node; }}\n"
        "const unrelated = this.refs.fake;\n"
    )
    (root / "Demo.jsx").write_text(source)
    result = _repair_react_this_refs(root, ["Demo.jsx"], None)["Demo.jsx"]
    assert "this.input.focus()" in result and "this.input = node" in result
    assert "'this.refs.input'" in result and "// this.refs.input" in result
    assert "/this.refs.input/" in result and "this.refs.fake" in result
    negative = "const x = this.refs.unrelated;\n"
    (root / "Negative.jsx").write_text(negative)
    assert _repair_react_this_refs(root, ["Negative.jsx"], None) == {}


