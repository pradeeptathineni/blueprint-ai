def test_stale_target_and_postcondition_failure_restore_exactly(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    from blueprint_ai.evolution import engine
    from blueprint_ai.safety import ProcessResult
    from blueprint_ai.sandbox import Execution, SandboxEvidence

    stale = _repository(tmp_path / "stale", _rust_files("2021"))
    stale_plan = plan_evolution(stale, ["rust/edition=2024"])
    (stale / "Cargo.toml").write_text((stale / "Cargo.toml").read_text() + "# changed\n")
    with pytest.raises(ValueError, match="stale evolution plan"):
        apply_evolution(stale, stale_plan, dry_run=True, run_blueprint_review=False)

    root = _repository(tmp_path / "postcondition", _rust_files("2018"))
    plan = plan_evolution(root, ["rust/edition=2021"])
    before = project_fingerprint(root)

    def fake_execute(command, _execution_root, policy, **_kwargs):
        result = ProcessResult(
            0,
            "cargo 1.98.1\n" if command[-1] == "--version" else "fixed\n",
            "",
            False,
            False,
        )
        evidence = SandboxEvidence(
            backend="host",
            tool="cargo",
            policy=policy,
            teardown=True,
            exit_code=0,
        )
        return Execution(result, evidence)

    monkeypatch.setattr(engine, "execute", fake_execute)
    monkeypatch.setattr(
        engine,
        "_tool_command",
        lambda _root, _tool, _policy, requested=None: requested or "cargo",
    )
    real_postcondition = engine._evaluate_postcondition

    def fail_after_native(workspace, condition):
        if condition.id == "rust/edition-2021":
            from blueprint_ai.evolution.models import EvolutionVerification

            return EvolutionVerification(
                id=condition.id,
                status="failed",
                detail="adversarial postcondition failed after native success",
            )
        return real_postcondition(workspace, condition)

    monkeypatch.setattr(engine, "_evaluate_postcondition", fail_after_native)
    with pytest.raises(RuntimeError, match="postcondition failed after native success"):
        apply_evolution(
            root,
            plan,
            policy=SandboxPolicy(backend="host", trusted=True, writable=True),
            run_blueprint_review=False,
        )
    assert project_fingerprint(root) == before

    failed = apply_evolution(
        root,
        plan,
        policy=SandboxPolicy(backend="host", trusted=True, writable=True),
        run_blueprint_review=False,
        report_failures=True,
    )
    assert failed.status == "failed"
    assert any(
        item.id == "evolution/recovery" and item.status == "passed" for item in failed.verifications
    )


