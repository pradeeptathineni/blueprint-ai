def test_module_tool_routing_and_fixture_exclusion(tmp_path: Path) -> None:
    for component in ("one", "two"):
        write(tmp_path, f"{component}/pyproject.toml", f'[project]\nname="{component}"\n')
        write(tmp_path, f"{component}/app.py", "import os\n")
        write(tmp_path, f"{component}/tests/fixtures/invalid.py", "invalid : :\n")
    adapters = applicable_adapters(discover_project(tmp_path), "code-quality")
    ruffs = [a for a in adapters if a.name.startswith("ruff")]
    assert {a.working_directory for a in ruffs} == {"one", "two"}
    assert all(
        "--no-cache" in a.args and not any("invalid.py" in arg for arg in a.args) for a in ruffs
    )


