def write(root: Path, path: str, text: str) -> None:
    file = root / path
    file.parent.mkdir(parents=True, exist_ok=True)
    file.write_text(text)


def test_nested_components_do_not_learn_roles_from_fixtures(tmp_path: Path) -> None:
    write(
        tmp_path, "backend/pyproject.toml", '[project]\nname="backend"\ndependencies=["fastapi"]\n'
    )
    write(tmp_path, "frontend/package.json", '{"name":"web","dependencies":{"react":"*"}}')
    write(tmp_path, "fixtures/requirements.txt", "# autogenerated\napache-airflow\ncrewai\n")
    write(tmp_path, "frontend/Sparkles.svelte", "<h1>Sparkles</h1>")
    facts = discover_project(tmp_path)
    assert {"full-stack", "api", "web-app"} <= set(facts.project_types)
    assert not {"ai-agent", "data-pipeline"} & set(facts.project_types)
    owner = facts.graph.owner("backend/service.py")
    assert owner is not None and owner.id == "backend"
    assert facts.graph.scope("fixtures/requirements.txt") == "fixture"


