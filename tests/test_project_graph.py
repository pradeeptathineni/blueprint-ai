def test_generated_contract_relationship_is_hash_bound(tmp_path: Path) -> None:
    import hashlib
    import json

    write(tmp_path, "backend/openapi.json", "{}\n")
    write(tmp_path, "frontend/src/generated/api.d.ts", 'export type Health = "ok"\n')
    paths = ["backend/openapi.json", "frontend/src/generated/api.d.ts"]
    hashes = {p: hashlib.sha256((tmp_path / p).read_bytes()).hexdigest() for p in paths}
    write(
        tmp_path,
        ".blueprint-ai/genesis.json",
        json.dumps(
            {
                "schema_version": "1.0",
                "result": {"files": hashes},
                "graph": {
                    "relationships": [
                        {
                            "source": paths[0],
                            "target": paths[1],
                            "kind": "generated-client",
                            "evidence": {"file": paths[0], "kind": "provider", "detail": "test"},
                        }
                    ]
                },
            }
        ),
    )
    graph = discover_project(tmp_path).graph
    assert any(e.kind == "generated-client" for e in graph.relationships)
    write(tmp_path, paths[1], 'export type Health = "changed"\n')
    graph = discover_project(tmp_path).graph
    assert not any(e.kind == "generated-client" for e in graph.relationships)
    assert any("drift" in diagnostic for diagnostic in graph.diagnostics)


def test_large_context_reserves_real_source_and_deduplicates_reads(tmp_path: Path) -> None:
    for i in range(220):
        write(tmp_path, f"component{i}/pyproject.toml", f'[project]\nname="component{i}"\n')
        write(
            tmp_path, f"component{i}/app.py", f"def calculate_{i}(value):\n    return value * {i}\n"
        )
    write(tmp_path, "tests/test_invariant.py", "def test_invariant():\n    assert 2 + 2 == 4\n")
    facts = discover_project(tmp_path)
    builder = ContextBuilder(tmp_path, 2000)
    architecture = builder.build("architecture", facts, [])
    testing = builder.build("testing", facts, [])
    assert "BEGIN_UNTRUSTED_FILE" in architecture and "def calculate_" in architecture
    assert "test_invariant" in testing
    assert architecture != testing
    assert len(architecture) <= 8000 and len(testing) <= 8000
    assert builder.metrics["files_read"] <= 48
    before = builder.metrics["files_read"]
    assert builder.build("testing", facts, []) == testing
    assert builder.metrics["files_read"] == before


def test_review_is_read_only_with_real_ruff(tmp_path: Path) -> None:
    write(tmp_path, "pyproject.toml", '[project]\nname="sample"\n')
    write(tmp_path, "app.py", "import os\n")
    before = sorted(p.relative_to(tmp_path).as_posix() for p in tmp_path.rglob("*"))
    context, _ = make_context(tmp_path, blueprints=["code-quality"], model_mode="off")
    result = review(context)
    assert any(t.name == "ruff" and t.outcome == "finding" for r in result.results for t in r.tools)
    assert before == sorted(p.relative_to(tmp_path).as_posix() for p in tmp_path.rglob("*"))
    assert result.metadata and result.metadata.analyzer_source_sha256
