def test_dependency_alias_merge_keeps_package_scope_and_evidence() -> None:
    rows = []
    for file, rule, aliases in (
        ("uv.lock", "GHSA-aaaa-bbbb-cccc", ["CVE-2025-12345"]),
        ("requirements.txt", "PYSEC-2025-99", ["GHSA-aaaa-bbbb-cccc"]),
    ):
        rows.append(
            Finding(
                blueprint="supply-chain",
                category="dependency-vulnerability",
                source="osv",
                message=rule,
                recommendation="Upgrade",
                rule_id=rule,
                file=file,
                component="backend",
                advisory_aliases=aliases,
                locations=[file],
                tool_metadata={"package": "foo", "ecosystem": "PyPI", "installed_version": "1"},
            )
        )
    distinct = rows[0].model_copy(deep=True)
    distinct.tool_metadata["package"] = "bar"
    rows.append(distinct)
    merged = deduplicate(rows, [])
    assert len(merged) == 2
    assert len({item.fingerprint for item in merged}) == 2
    assert next(r for r in merged if r.tool_metadata["package"] == "foo").locations == [
        "requirements.txt",
        "uv.lock",
    ]


